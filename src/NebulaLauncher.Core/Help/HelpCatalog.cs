/// <summary>
/// 一条内置帮助。正文是纯文本（段落用空行分隔），不解析 Markdown：
/// 帮助页不联网、不渲染富文本，内容才能随启动器一起离线可用。
/// </summary>
/// <param name="Id">稳定标识，用于记住上次阅读位置。</param>
/// <param name="Title">标题，搜索权重最高。</param>
/// <param name="Category">分类，见 <see cref="HelpCatalog.Categories"/>。</param>
/// <param name="Keywords">同义词与常见叫法，搜索权重高于正文——用户更可能记口语而不是我们的措辞。</param>
/// <param name="Body">正文，段落用空行分隔。</param>
public sealed record HelpTopic(string Id, string Title, string Category, string Keywords, string Body);

