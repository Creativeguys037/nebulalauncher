    /// <summary>全部条目。列表不超过 30 条，直接用普通列表即可，不需要虚拟化。</summary>
    public static IReadOnlyList<HelpTopic> Topics { get; } = BuildTopics();

    /// <summary>
    /// 按关键词过滤并排序。空查询返回全部（保持原顺序）。
    ///
    /// 权重：关键词 1.5 &gt; 标题 1.0 &gt; 正文 0.5。关键词最高的理由：
    /// 用户搜「整合包」时，正文里顺带提到这个词的条目不该排在标题就是整合包的条目前面。
    /// </summary>
    public static IReadOnlyList<HelpTopic> Filter(IEnumerable<HelpTopic>? topics, string? query)
    {
        if (topics is null)
        {
            return Array.Empty<HelpTopic>();
        }

        var all = topics as IReadOnlyList<HelpTopic> ?? topics.ToList();
        var keyword = query?.Trim();

        if (string.IsNullOrEmpty(keyword))
        {
            return all;
        }

        var scored = new List<(HelpTopic Topic, double Score, int Index)>(all.Count);

        for (var index = 0; index < all.Count; index++)
        {
            var topic = all[index];
            var score = 0d;

            if (topic.Title.Contains(keyword, StringComparison.OrdinalIgnoreCase))
            {
                score += 1.0;
            }

            if (topic.Keywords.Contains(keyword, StringComparison.OrdinalIgnoreCase))
            {
                score += 1.5;
            }

            if (topic.Body.Contains(keyword, StringComparison.OrdinalIgnoreCase))
            {
                score += 0.5;
            }

            if (score > 0)
            {
                scored.Add((topic, score, index));
            }
        }

        // 同分时保持原顺序（OrderByDescending 是稳定排序，这里再按 Index 兜底一次）。
        return scored
            .OrderByDescending(item => item.Score)
            .ThenBy(item => item.Index)
            .Select(item => item.Topic)
            .ToList();
    }

